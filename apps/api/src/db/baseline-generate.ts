/**
 * `pnpm db:baseline`: writes drizzle/baseline.sql, the whole current schema as few statements as
 * possible, which migrate() applies to an empty database instead of replaying every migration.
 * drizzle-kit generates the schema from schema.ts; its foreign keys (separate ALTER TABLEs, one
 * DSQL transaction each) are folded into their CREATE TABLEs, ordered so each table comes after
 * the ones it references. The first line names the last migration it covers. Run it after
 * `pnpm db:generate`; migrate.test.ts fails while it's stale.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const out = mkdtempSync(join(tmpdir(), 'baseline-'));
try {
  execFileSync(
    'pnpm',
    [
      'exec',
      'drizzle-kit',
      'generate',
      '--dialect',
      'postgresql',
      '--schema',
      './src/db/schema.ts',
      '--out',
      out,
      '--name',
      'baseline',
    ],
    { cwd: root, stdio: 'inherit' },
  );
  const file = readdirSync(out).find((f) => f.endsWith('.sql'))!;
  const statements = readFileSync(join(out, file), 'utf8')
    .split('--> statement-breakpoint')
    .map((s) => s.trim().replace(/;$/, ''))
    .filter(Boolean);

  const tables = new Map<string, string>();
  const references = new Map<string, Set<string>>();
  const indexes: string[] = [];
  for (const s of statements) {
    const table = /^CREATE TABLE "([^"]+)"/.exec(s)?.[1];
    if (table) {
      tables.set(table, s);
      references.set(table, new Set());
      continue;
    }
    const fk =
      /^ALTER TABLE "([^"]+)" ADD (CONSTRAINT .* FOREIGN KEY .* REFERENCES "public"\."([^"]+)".*)$/.exec(
        s,
      );
    if (fk) {
      const [, from, constraint, to] = fk as unknown as [string, string, string, string];
      const create = tables.get(from)!;
      if (!/\n\)$/.test(create)) throw new Error(`Can't add ${constraint} to ${from}`);
      tables.set(from, create.replace(/\n\)$/, `,\n\t${constraint}\n)`));
      if (to !== from) references.get(from)!.add(to);
      continue;
    }
    if (/^CREATE (UNIQUE )?INDEX /.test(s)) {
      indexes.push(s);
      continue;
    }
    throw new Error(`Unexpected statement in the generated schema: ${s.slice(0, 80)}`);
  }

  // Each table after the tables it references.
  const ordered: string[] = [];
  const visit = (table: string, path: string[]) => {
    if (ordered.includes(table)) return;
    if (path.includes(table))
      throw new Error(`Foreign key cycle: ${[...path, table].join(' -> ')}`);
    for (const to of references.get(table)!) visit(to, [...path, table]);
    ordered.push(table);
  };
  for (const table of [...tables.keys()].sort()) visit(table, []);

  const journal: { entries: { tag: string }[] } = JSON.parse(
    readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8'),
  );
  const covers = journal.entries.at(-1)!.tag;
  const body = [...ordered.map((t) => tables.get(t)!), ...indexes].join(
    ';\n--> statement-breakpoint\n',
  );
  writeFileSync(
    join(root, 'drizzle/baseline.sql'),
    `-- covers: ${covers}\n-- Generated by \`pnpm db:baseline\` (src/db/baseline-generate.ts). Don't edit.\n${body};\n`,
  );
  console.log(
    `drizzle/baseline.sql: ${ordered.length} tables, ${indexes.length} indexes, covers ${covers}`,
  );
} finally {
  rmSync(out, { recursive: true, force: true });
}
